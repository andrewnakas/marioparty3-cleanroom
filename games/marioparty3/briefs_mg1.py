def fit(b, edge=None, pad=0):
    """Painter: the brief drawn into the bounding box of the kept alpha outline (whole image when there is none);
    `edge` = colour of a 1 px rim just inside the outline."""
    def fn(w, h, d, alpha):
        if alpha is None:
            return facepaint.render(b, w, h)
        a = np.asarray(alpha) >= 96
        ys, xs = np.nonzero(a)
        out = np.zeros((h, w, 4), np.float32)
        out[..., :3] = b["base"] if not isinstance(b["base"], dict) else b["base"]["grad"][0]
        out[..., 3] = alpha
        if len(ys):
            y0, y1 = max(0, ys.min() - pad), min(h, ys.max() + 1 + pad)
            x0, x1 = max(0, xs.min() - pad), min(w, xs.max() + 1 + pad)
            out[y0:y1, x0:x1, :3] = facepaint.render(b, x1 - x0, y1 - y0)[..., :3]
        if edge is not None:
            p = np.pad(a, 1)
            inner = p[:-2, 1:-1] & p[2:, 1:-1] & p[1:-1, :-2] & p[1:-1, 2:]
            out[a & ~inner, :3] = edge
        return out
    return fn


def texts(base, *items):
    """Painter: a brief (or painter) with several typeset words; item = (text, top, bottom, edge, box, options)."""
    def fn(w, h, d, alpha):
        out = base(w, h, d, alpha) if callable(base) else facepaint.render(base, w, h, alpha=alpha)
        out = np.asarray(out, np.float32)
        for text, top, bottom, edge, box, opt in items:
            x0, y0, x1, y1 = int(box[0] * w), int(box[1] * h), int(round(box[2] * w)), int(round(box[3] * h))
            g = typeset(x1 - x0, y1 - y0, text, top, bottom, edge, **opt)
            a = g[..., 3:] / 255
            out[y0:y1, x0:x1, :3] = out[y0:y1, x0:x1, :3] * (1 - a) + g[..., :3] * a
        return out
    return fn


