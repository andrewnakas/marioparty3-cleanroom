def crisp(text, c, th=0.9, dark_bg=(8, 8, 10)):
    """Painter for tiny words/digits (8-10 px high): one flat colour, hard edges, no outline."""
    def fn(w, h, d, alpha):
        g = typeset(w, h, text, c, c, c, th=th, pad=0, edge_px=0.01)
        on = g[..., 3] >= 105
        out = np.zeros((h, w, 4), np.float32)
        out[..., :3] = c
        if alpha is None:
            out[~on, :3] = dark_bg
            out[..., 3] = 255
        else:
            out[..., 3] = np.where(on, 255, 0)
        return out
    return fn


