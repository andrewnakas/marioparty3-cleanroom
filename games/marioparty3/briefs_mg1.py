def word(text, x0, x1, cy, sy, w, c):
    """A word in the stroke letters above, spread over x0..x1 (I and ! take half a cell)."""
    unit = (x1 - x0) / sum(_NARROW.get(ch, 1.0) for ch in text)
    ops, x = [], x0
    for ch in text:
        cw = unit * _NARROW.get(ch, 1.0)
        ops += glyph(ch, x + cw / 2, cy, unit * 0.4, sy, w, c)
        x += cw
    return ops


def glyph(ch, cx, cy, sx, sy, w, c):
    """A letter as strokes: centre, half-width scale, half-height, stroke width."""
    return [L([(cx + x * sx, cy + y * sy) for x, y in st], w, c) for st in _GL[ch]]


