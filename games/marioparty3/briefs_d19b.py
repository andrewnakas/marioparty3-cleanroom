def _opaque(fn):
    """Kept outline plus our own letters (white on black), so no stroke is clipped by the coarse outline."""
    def out_fn(w, h, d, alpha):
        out = fn(w, h, d, None)
        lit = np.where(out[..., :3].sum(-1) > 150, 255, 0)
        out[..., 3] = np.maximum(lit, alpha if alpha is not None else 255)
        return out
    return out_fn


