# ------------------------------------------------------------------ helpers
def multi(base, *items):
    """Painter: a brief with several typeset words laid over it. item = (text, top, bottom, edge, box, options)."""
    def fn(w, h, d, alpha):
        out = np.asarray(facepaint.render(base, w, h, alpha=alpha), np.float32).copy()
        for text, top, bottom, edge, box, opt in items:
            x0, y0, x1, y1 = int(box[0] * w), int(box[1] * h), int(round(box[2] * w)), int(round(box[3] * h))
            g = typeset(x1 - x0, y1 - y0, text, top, bottom, edge, **opt)
            a = np.clip(g[..., 3:] / 255, 0, 1)
            out[y0:y1, x0:x1, :3] = out[y0:y1, x0:x1, :3] * (1 - a) + g[..., :3] * a
        return out
    return fn


def fit(ops, x0, y0, x1, y1):
    """The same primitives squeezed into the box (x0, y0, x1, y1) of the picture."""
    sx, sy = x1 - x0, y1 - y0
    out = []
    for op in ops:
        o = dict(op)
        for k in ("e", "ring", "sphere", "arc", "clip"):
            if o.get(k):
                v = list(o[k])
                o[k] = [x0 + v[0] * sx, y0 + v[1] * sy, v[2] * sx, v[3] * sy] + v[4:]
        for k in ("poly", "line"):
            if k in o:
                o[k] = [(x0 + x * sx, y0 + y * sy) for x, y in o[k]]
        if "rect" in o:
            a, b, c, e = o["rect"]
            o["rect"] = [x0 + a * sx, y0 + b * sy, x0 + c * sx, y0 + e * sy]
        if "w" in o:
            o["w"] = o["w"] * min(sx, sy)
        out.append(o)
    return out


def frame(c, t=0.08):
    return [R(0, 0, 1, t, c), R(0, 1 - t, 1, 1, c), R(0, 0, t, 1, c), R(1 - t, 0, 1, 1, c)]


def lighter(c, k=70):
    return [min(255, v + k) for v in c]


def darker(c, k=0.6):
    return [int(v * k) for v in c]


