def _hexes(n, c, w):
    """Shell plates: rows of hexagon outlines."""
    ops = []
    s = 1.0 / n
    for j in range(-1, n * 2 + 1):
        for i in range(-1, n + 1):
            cx, cy = (i + (0.5 if j % 2 else 0)) * s + s / 2, j * s / 2 + s / 4
            pts = [(cx + s * 0.34 * math.cos(math.radians(a)), cy + s * 0.5 * math.sin(math.radians(a))) for a in range(0, 361, 60)]
            ops.append(L(pts, w, c))
    return ops


