def bust(who):
    """Stone bust: our drawn head in one stone tone (light and shade from the drawing's own brightness)."""
    key = [0, 255, 0]
    b = I.head(who, bg=key)

    def fn(w, h, d, alpha):
        img = np.asarray(facepaint.render(b, w, h), np.float32)[..., :3]
        lum = img.mean(-1, keepdims=True) / 255
        out = np.zeros((h, w, 4), np.float32)
        out[..., :3] = _STONE * (0.45 + 0.6 * lum)
        bgm = np.abs(img - np.array(key, np.float32)).sum(-1) < 60
        yy = np.linspace(1.0, 0.7, h, dtype=np.float32)[:, None]
        out[bgm, :3] = (_STONE * 0.8 * yy[..., None])[np.nonzero(bgm)[0], 0]
        out[..., 3] = 255 if alpha is None else alpha
        return out
    return fn


