def dotted(paths, extra=(), step=0.045):
    """Painter: a star-chart figure, white dots along our own outline paths on black."""
    def fn(w, h, d, alpha):
        out = np.zeros((h, w, 4), np.float32)
        out[..., 3] = 255
        for pts in paths:
            for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
                n = max(1, int(math.hypot(x1 - x0, y1 - y0) / step))
                for i in range(n):
                    x, y = int((x0 + (x1 - x0) * i / n) * w), int((y0 + (y1 - y0) * i / n) * h)
                    if 0 <= x < w and 0 <= y < h:
                        out[y, x, :3] = 255
        for x0, y0, x1, y1 in extra:
            out[int(y0 * h):int(y1 * h), int(x0 * w):int(x1 * w), :3] = 255
        return out
    return fn


