# ------------------------------------------------------------------ helpers
def bf(base, *ops):
    """brief() that accepts nested op lists."""
    return I._b(base, *ops)


def words(base, *items, own=False):
    """Painter: a brief with typeset words laid over it; items = (text, box, (top, bottom, edge), options)."""
    def fn(w, h, d, alpha):
        out = np.array(facepaint.render(base, w, h, alpha=None if own else alpha), np.float32)
        for text, box, cols, opt in items:
            x0, y0, x1, y1 = int(box[0] * w), int(box[1] * h), int(round(box[2] * w)), int(round(box[3] * h))
            g = typeset(x1 - x0, y1 - y0, text, *cols, **opt)
            a = g[..., 3:] / 255
            out[y0:y1, x0:x1, :3] = out[y0:y1, x0:x1, :3] * (1 - a) + g[..., :3] * a
        return out
    return fn


def fit(b, top=False, grow=0.0):
    """Painter: the brief drawn inside the bounding box of the kept alpha outline (whole image when there is none).
    top = keep the drawing square (in pixels) and hang it from the top of the box (things rising out of a hole)."""
    def fn(w, h, d, alpha):
        box = (0.0, 0.0, 1.0, 1.0)
        if alpha is not None:
            a = np.asarray(alpha) >= 128
            if a.any():
                ys, xs = np.where(a.any(1))[0], np.where(a.any(0))[0]
                box = (xs[0] / w - grow, ys[0] / h - grow, (xs[-1] + 1) / w + grow, (ys[-1] + 1) / h + grow)
                if top:
                    box = (box[0], box[1], box[2], box[1] + (box[2] - box[0]) * w / h)
        return facepaint.render(brief(b["base"], *I.place(b, box)), w, h, alpha=alpha)
    return fn


def petals(cx, cy, n, r, pr, c, rot=-90.0, ax=1.0):
    return [E((cx + r * math.cos(math.radians(rot + 360 * i / n)) * ax, cy + r * math.sin(math.radians(rot + 360 * i / n))), (pr * ax, pr), c=c)
            for i in range(n)]


def burst(cx, cy, ro, ri, n, rot=-90.0):
    return [(cx + (ro if i % 2 == 0 else ri) * math.cos(math.radians(rot + 180 * i / n)),
             cy + (ro if i % 2 == 0 else ri) * math.sin(math.radians(rot + 180 * i / n))) for i in range(2 * n)]


def arrow(path, c=RED, w=0.13, head=0.2, ax=1.0):
    """Polyline arrow: the stem follows the path, the head continues the last segment."""
    (x0, y0), (x1, y1) = path[-2], path[-1]
    dx, dy = (x1 - x0) / ax, y1 - y0
    n = math.hypot(dx, dy) or 1.0
    ux, uy = dx / n, dy / n
    tip = (x1 + ux * head * ax, y1 + uy * head)
    return [L(list(path), w, c), P([tip, (x1 - uy * head * 0.8 * ax, y1 + ux * head * 0.8), (x1 + uy * head * 0.8 * ax, y1 - ux * head * 0.8)], c)]


def block_arrow(c, flip=False, up=False, edge=None):
    pts = [(0.08, 0.36), (0.52, 0.36), (0.52, 0.16), (0.94, 0.5), (0.52, 0.84), (0.52, 0.64), (0.08, 0.64)]
    if flip:
        pts = [(1 - x, y) for x, y in pts]
    if up:
        pts = [(y, 1 - x) for x, y in pts]
    out = []
    if edge is not None:
        out.append(L(pts + pts[:1], 0.09, edge))
    return out + [P(pts, c)]


def star(cx, cy, r, c, edge=None, ax=1.0):
    out = [P(star_pts(cx, cy, r * 1.16, r * 0.56, aspect=ax), edge)] if edge is not None else []
    return out + [P(star_pts(cx, cy, r, r * 0.46, aspect=ax), c)]


